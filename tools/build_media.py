"""Resize the canonical images from the old site and write data/media.js.

Usage:  python tools/build_media.py ["D:/Website Jos Tiebosch"]

Output:
  assets/img/full/<id>.jpg   (max 1600 px, clippings max 2400 px)
  assets/img/thumb/<id>.jpg  (max 520 px)
  data/media.js              (window.MEDIA = {...})
"""
import json
import os
import re
import sys
import unicodedata

from PIL import Image, ImageOps

sys.path.insert(0, os.path.dirname(__file__))
import catalogue as C  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else r"D:\Website Jos Tiebosch"
FULL = os.path.join(ROOT, "assets", "img", "full")
THUMB = os.path.join(ROOT, "assets", "img", "thumb")


def slug(text):
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def find_source(name):
    """Old file names contain cp1252 characters; match leniently."""
    path = os.path.join(SRC, name)
    if os.path.exists(path):
        return path
    want = slug(name)
    for f in os.listdir(SRC):
        if slug(f) == want:
            return os.path.join(SRC, f)
    raise FileNotFoundError(name)


done = {}


def process(source, image_id, long_side=1600):
    """Write full + thumb versions; return {id, w, h}."""
    if image_id in done:
        return done[image_id]
    im = Image.open(find_source(source))
    im.seek(0)
    im = ImageOps.exif_transpose(im).convert("RGB")
    full = im.copy()
    full.thumbnail((long_side, long_side), Image.LANCZOS)
    full.save(os.path.join(FULL, image_id + ".jpg"), quality=84, optimize=True, progressive=True)
    thumb = im.copy()
    thumb.thumbnail((520, 520), Image.LANCZOS)
    thumb.save(os.path.join(THUMB, image_id + ".jpg"), quality=78, optimize=True, progressive=True)
    info = {"id": image_id, "w": full.width, "h": full.height}
    done[image_id] = info
    return info


def main():
    os.makedirs(FULL, exist_ok=True)
    os.makedirs(THUMB, exist_ok=True)
    media = {"certificates180": [], "certificatesOther": [], "clippings": [], "albums": [],
             "portraits": {}, "videos": []}

    for season, count, src, date in C.CERT_180:
        info = process(src, "cert-180-" + season)
        media["certificates180"].append({**info, "season": season, "count": count, "date": date})

    for cid, title, caption, year, src in C.CERT_OTHER:
        info = process(src, "cert-" + cid)
        media["certificatesOther"].append({**info, "title": title, "caption": caption, "year": year})

    for cid, title, src in C.CLIPPINGS:
        info = process(src, "knipsel-" + cid, long_side=2400)
        media["clippings"].append({**info, "title": title})

    for album in C.ALBUMS:
        photos = []
        for i, (src, caption) in enumerate(album["photos"], 1):
            info = process(src, f"{album['id']}-{i:02d}")
            photos.append({**info, "caption": caption})
        entry = {k: v for k, v in album.items() if k != "photos"}
        entry["photos"] = photos
        media["albums"].append(entry)
    media["albums"].sort(key=lambda a: a["year"])

    for pid, src, caption in C.PORTRAITS:
        media["portraits"][pid] = {**process(src, "portret-" + pid), "caption": caption}

    media["videos"] = [{"youtube": vid, "title": title} for vid, title in C.VIDEOS]

    out = os.path.join(ROOT, "data", "media.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_media.py - do not edit by hand.\n")
        f.write("window.MEDIA = ")
        json.dump(media, f, ensure_ascii=False, indent=1)
        f.write(";\n")

    total = sum(os.path.getsize(os.path.join(d, x)) for d in (FULL, THUMB) for x in os.listdir(d))
    print(f"{len(done)} images, {total / 1e6:.1f} MB -> {out}")


if __name__ == "__main__":
    main()
